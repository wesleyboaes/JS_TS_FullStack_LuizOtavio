/* Comparing Operators
> greater than
>= greater than equals
< less than
<= less than equals
== equals (value)
=== strictly equal (value and type)
!= different (value)
!== strictly different (value and type)
*/
console.log(10 > 5);

const num1 = 10; // number
const num2 = "10"; // string
const compare = num1 == num2;

console.log(compare);

const compare2 = num1 === num2;

console.log(compare2);
